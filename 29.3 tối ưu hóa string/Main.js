// trim() xóa khoảng trắng đầu cuối
let s11="   hello world  ";
let s12 = s11.trim()
console.log(s11);
console.log(s11.length);
console.log(s12);
console.log(s12.length);
//trimEnd() xóa khoảng trắng cuối
let s13=" hello wolrd   ";
let s14 = s13.trimEnd()
console.log(s13);
console.log(s13.length);
console.log(s14);
console.log(s14.length);
//trimStart() xóa khoảng trắng ở đầu
let s15="   hello world";
let s16 = s15.trimStart()
console.log(s15);
console.log(s15.length);
console.log(s16);
console.log(s16.length);

